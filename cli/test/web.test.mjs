import test from 'node:test';
import assert from 'node:assert/strict';
import {webAnswer, webRequest, articleTitle} from '../../site/web.js';
import {localAnswer} from '../../site/b1.js';

test('percentage word problems produce numeric answers with the calculation',()=>{
  assert.deepEqual(localAnswer('30% tip of 100 is?'),['Tip: 30. Total: 130.\n100 × 30 / 100 = 30','local_calculator']);
  assert.deepEqual(localAnswer('20% off $1,000'),['Discount: $200. Total: $800.\n1000 × 20 / 100 = 200','local_calculator']);
  assert.equal(localAnswer('I heard a story about 30% tips'),null);
});
test('web requests accept explicit commands and refuse arbitrary reading URLs',()=>{
  assert.deepEqual(webRequest('search the web for percentages'),{mode:'search',query:'percentages'});
  assert.deepEqual(webRequest('/web read https://en.wikipedia.org/wiki/Percentage'),{mode:'read',query:'https://en.wikipedia.org/wiki/Percentage'});
  assert.equal(webRequest('I love pancakes'),null);
  for(const url of ['http://127.0.0.1/private','https://en.wikipedia.org.evil.example/wiki/a','https://user@en.wikipedia.org/wiki/a','https://en.wikipedia.org:444/wiki/a','https://en.wikipedia.org/w/api.php'])assert.throws(()=>articleTitle(url));
});
test('lookups send only the query, omit cookies, and retain source links',async()=>{
  let seen;
  const fetcher=async(url,options)=>{seen={url:new URL(url),options};return {ok:true,text:async()=>JSON.stringify({query:{pages:[{ns:0,title:'Percentage',extract:'A percentage is a fraction of 100.',index:1}]}})};};
  const result=await webAnswer({mode:'search',query:'30 percent'},fetcher,undefined,{duckduckgo:false,proxy:false,key:undefined});
  assert.equal(seen.url.hostname,'en.wikipedia.org');assert.equal(seen.url.searchParams.get('gsrsearch'),'30 percent');
  assert.equal(seen.options.credentials,'omit');assert.equal(seen.options.redirect,'error');
  assert.match(result.text,/not generated by the model/);assert.match(result.text,/https:\/\/en.wikipedia.org\/wiki\/Percentage/);
  await assert.rejects(webAnswer({mode:'search',query:'a'.repeat(301)},fetcher),/1–300/);
  await assert.rejects(webAnswer({mode:'search',query:'a'},async()=>({ok:false,status:429,headers:{get:()=> '60'}}),undefined,{duckduckgo:false,proxy:false,key:undefined}),/rate-limiting/);
  await assert.rejects(webAnswer({mode:'search',query:'a'},()=>{throw new Error('should not retry during cooldown');}),/Try again/);
});

test('natural search requests route to search without relying on model-generated tool calls',()=>{
  for(const phrase of ['can you search up percents','could you please search for percents','please look up percents','search percents','google percents','can you search the web for percents'])
    assert.deepEqual(webRequest(phrase),{mode:'search',query:'percents'},phrase);
  for(const phrase of ['how do I search a file?','I searched up percents yesterday','can you explain percents','what is a search engine?'])
    assert.equal(webRequest(phrase),null,phrase);
});

test('Node uses the configured Worker without a local API key and preserves results',async()=>{
  let seen;
  const fetcher=async(url,options)=>{
    seen={url,options};
    return {ok:true,text:async()=>JSON.stringify({results:[{title:'Percentage',url:'https://example.org/percentage',text:'Percent means per hundred.'}]})};
  };
  const result=await webAnswer(webRequest('can you search up percents'),fetcher,undefined,{key:undefined});
  assert.equal(seen.url,'https://somewhat.chatgpt-ai-5-2o2.workers.dev/search');
  assert.deepEqual(JSON.parse(seen.options.body),{query:'percents'});
  assert.equal(seen.options.headers.Authorization,undefined);
  assert.equal(seen.options.headers.Origin,'https://kelus-b1.web.app');
  assert.equal(seen.options.credentials,'omit');
  assert.equal(result.engine,'langsearch');
  assert.match(result.text,/https:\/\/example.org\/percentage/);
});

test('someone in danger gets the fixed reply, even when asking for a search', () => {
  assert.equal(webRequest('search for how to kill myself'), null);
  assert.equal(webRequest('/web i want to die'), null);
  assert.equal(localAnswer('search for how to kill myself')[1], 'crisis_support');
  assert.deepEqual(webRequest('search for suicide squad cast'), { mode: 'search', query: 'suicide squad cast' });
  assert.deepEqual(webRequest('search for otters'), { mode: 'search', query: 'otters' });
});
