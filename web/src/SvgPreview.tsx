import { useEffect, useState } from 'react';
import { extractSvg } from './engine';


export function SvgPreview({ reply }: { reply: string }) {
  const [url, setUrl] = useState<string>();
  useEffect(() => {
    let svg: string;
    try { svg = extractSvg(reply); } catch { return; }
    const objectUrl = URL.createObjectURL(new Blob([svg], { type: 'image/svg+xml' }));
    setUrl(objectUrl);
    return () => URL.revokeObjectURL(objectUrl);
  }, [reply]);
  if (!url) return null;
  return (
    <figure className="svg-preview">
      <img src={url} alt="SVG generated by Kani" width={256} height={256} />
      <figcaption>Generated SVG · review the source below</figcaption>
      <a href={url} download="kani-image.svg">Download SVG</a>
    </figure>
  );
}
