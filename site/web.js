import { normalized, supportReply } from './support.js';
const API='https://en.wikipedia.org/w/api.php', DDG='https://api.duckduckgo.com/';
const PROXY='https://somewhat.chatgpt-ai-5-2o2.workers.dev/search', LANGSEARCH='https://api.langsearch.com/v1/web-search';
let retryAt=0;

export const SEARCH_PHRASE=/^(?:(?:please|(?:can|could|would|will) you(?: please)?)\s+)?(?:search(?:\s+(?:the\s+)?(?:web|internet|online|google|duckduckgo))?(?:\s+(?:for|up))?|look\s+up|google)\s+([\s\S]+)$/i;
export function webRequest(text) {
  if(supportReply(normalized(text)))return null; // someone in danger gets the fixed reply, not search results
  const command=text.trim().match(/^\/web\s+(?:(search|read)\s+)?([\s\S]+)$/i);
  if(command)return {mode:(command[1]||'search').toLowerCase(),query:command[2].trim()};
  const natural=text.trim().match(SEARCH_PHRASE);
  return natural?{mode:'search',query:natural[1].trim()}:null;
}
export function articleTitle(input) {
  if(!/^https?:/i.test(input))return input;
  const url=new URL(input);
  if(url.protocol!=='https:'||url.hostname!=='en.wikipedia.org'||url.port||url.username||url.password||!url.pathname.startsWith('/wiki/')||url.search)throw new Error('Article reading currently supports English Wikipedia article URLs or titles.');
  return decodeURIComponent(url.pathname.slice(6)).replaceAll('_',' ');
}
const options=signal=>({credentials:'omit',referrerPolicy:'no-referrer',redirect:'error',signal});


function instantAnswer(data) {
  const parts=[], related=[];
  for(const item of [...(data.Results||[]),...(data.RelatedTopics||[])])
    for(const topic of item.Topics||[item]) if(topic.Text&&topic.FirstURL&&related.length<5)related.push(`${topic.Text.slice(0,200)}\n${topic.FirstURL}`);
  if(typeof data.Answer==='string'&&data.Answer)parts.push(data.Answer.slice(0,600));
  if(data.AbstractText)parts.push(data.AbstractText.slice(0,2500)+(data.AbstractURL?`\nSource: ${data.AbstractSource||'link'} · ${data.AbstractURL}`:''));
  if(data.Definition)parts.push(data.Definition.slice(0,600)+(data.DefinitionURL?`\nSource: ${data.DefinitionSource||'link'} · ${data.DefinitionURL}`:''));
  if(!parts.length&&!related.length)return null;
  return 'DuckDuckGo instant answer — retrieved online, not generated by the model.\n\n'+(data.Heading?data.Heading+'\n':'')+parts.join('\n\n')
    +(related.length?(parts.length?'\n\n':'')+'Related:\n'+related.map((r,i)=>`[${i+1}] ${r}`).join('\n'):'')
    +(data.AbstractSource==='Wikipedia'?'\n\nWikipedia contributors · CC BY-SA 4.0.':'')+'\n\nResults from the DuckDuckGo Instant Answer API.';
}


const NODE=typeof process!=='undefined'&&Boolean(process.versions?.node);

async function webResults(query, fetcher, signal, key) {
  const response=await fetcher(key?LANGSEARCH:PROXY,{method:'POST',headers:{'Content-Type':'application/json',...(!key&&NODE?{Origin:'https://kelus-b1.web.app'}:{}),...(key?{Authorization:`Bearer ${key}`}:{})},
    body:JSON.stringify(key?{query,count:5,contents:{text:true}}:{query}),...options(signal)});
  const raw=await response.text();
  if(raw.length>600000)throw new Error('the response was too large');
  let data={};try{data=raw?JSON.parse(raw):{};}catch{throw new Error(`unexpected reply (${response.status})`);}
  if(!response.ok)throw new Error(data.error||`HTTP ${response.status}`);
  const pages=key?(data.data?.webPages?.value||[]).map(p=>({title:p.name,url:p.url,text:p.text??p.snippet,date:p.datePublished})):(data.results||[]);
  return pages.filter(p=>typeof p?.url==='string'&&(p.url.startsWith('https://')||p.url.startsWith('http://'))).slice(0,5)
    .map(p=>({title:String(p.title||p.url).slice(0,200),url:p.url,text:String(p.text||'').replace(/\s+/g,' ').trim().slice(0,1500),date:p.date?String(p.date).slice(0,10):null}));
}

function resultsText(results) {
  return 'Web search results (LangSearch) — retrieved online, not generated by the model.\n\n'
    +results.map((r,i)=>`[${i+1}] ${r.title}${r.date?` (${r.date})`:''}\n${r.text.length>400?r.text.slice(0,400)+'…':r.text}\n${r.url}`).join('\n\n')
    +'\n\nWeb pages can be wrong or out of date; check the sources.';
}


export async function webAnswer(request, fetcher=fetch, signal, {duckduckgo=NODE, proxy=true, key=NODE?process.env.LANGSEARCH_API_KEY:undefined}={}) {
  if(request?.mode!=='search'||!request.query||request.query.length>300)return wikipedia(request,fetcher,signal);
  const controller=new AbortController(), timer=setTimeout(()=>controller.abort(),20000);
  const abort=()=>controller.abort();signal?.addEventListener('abort',abort,{once:true});
  let note='';
  try {
    if(proxy||key) {
      try {
        const results=await webResults(request.query,fetcher,controller.signal,key);
        if(results.length)return {text:resultsText(results),sources:results,engine:'langsearch'};
        note='Web search found nothing for that. ';
      } catch(error) {
        if(signal?.aborted)throw new Error('Web lookup stopped or timed out.');
        note=`Web search failed: ${error.name==='AbortError'?'it timed out':error.message} `;
      }
    }
    if(duckduckgo) {
      try {
        const params=new URLSearchParams({q:request.query,format:'json',no_html:'1',skip_disambig:'1',no_redirect:'1',t:'kelus-kani'});
        const response=await fetcher(DDG+'?'+params,options(controller.signal));
        const raw=response.ok?await response.text():'';
        const data=raw&&raw.length<250000?JSON.parse(raw):null, text=data&&instantAnswer(data);
        const sources=data?.AbstractText&&data.AbstractURL?[{title:data.Heading||request.query,url:data.AbstractURL,text:data.AbstractText}]:[];
        if(text)return {text:(note?note+'\n\n':'')+text,sources,engine:'duckduckgo'};
        note+='DuckDuckGo had no instant answer for that. ';
      } catch(error) {
        if(signal?.aborted)throw new Error('Web lookup stopped or timed out.');
        note+='DuckDuckGo could not be reached. ';
      }
    }
  } finally {clearTimeout(timer);signal?.removeEventListener('abort',abort);}
  const result=await wikipedia(request,fetcher,signal);
  return {...result,text:(note?note.trim()+' Here is Wikipedia search instead.\n\n':'')+result.text};
}



const QUESTION_WORDS=new Set('a an the of is are was were be been what who whom whose when where which how why do does did tell me about please'.split(' '));
export const searchWords=query=>query.split(/\s+/).filter(word=>!QUESTION_WORDS.has(word.toLowerCase().replace(/[^\p{L}\p{N}]/gu,''))).join(' ')||query;
export const questionNames=query=>[...query.matchAll(/\p{Lu}[\p{L}'-]*(?:\s+(?:(?:of|the|and|de|von|van|da)\s+)*\p{Lu}[\p{L}'-]*)*/gu)]
  .map(match=>match[0]).filter(name=>name.length>2&&!QUESTION_WORDS.has(name.toLowerCase())).slice(0,2);

async function wikipedia(request, fetcher, signal) {
  if(Date.now()<retryAt)throw new Error(`Wikipedia is rate-limiting requests. Try again in ${Math.ceil((retryAt-Date.now())/60000)} minutes.`);
  if(!request?.query||request.query.length>300)throw new Error('Use a web query of 1–300 characters.');
  const params=new URLSearchParams({action:'query',format:'json',formatversion:'2',origin:'*',prop:'extracts|info',inprop:'url',explaintext:'1',exlimit:'3',exchars:'2500'});
  const lookups=[];
  if(request.mode==='read') lookups.push({titles:articleTitle(request.query),redirects:'1'});
  else {
    const names=questionNames(request.query);
    if(names.length) lookups.push({titles:names.join('|'),redirects:'1',exintro:'1'});
    lookups.push({generator:'search',gsrsearch:searchWords(request.query),gsrlimit:'3',gsrnamespace:'0',exintro:'1'});
  }
  const controller=new AbortController(), timer=setTimeout(()=>controller.abort(),15000);
  const abort=()=>controller.abort();signal?.addEventListener('abort',abort,{once:true});
  if(signal?.aborted)controller.abort();
  try {

    const agentHeader=typeof process!=='undefined'&&process.versions?.node?'User-Agent':'Api-User-Agent';
    const headers={[agentHeader]:'KelusKani/0.1 (https://github.com/KelusIDE/KelusModelB1)'};
    let pages=[];
    for(const lookup of lookups) {
      const query=new URLSearchParams(params);for(const [key,value] of Object.entries(lookup))query.set(key,value);
      const response=await fetcher(API+'?'+query,{headers,...options(controller.signal)});
      if(response.status===429) {
        const delay=Number(response.headers?.get('retry-after'));
        retryAt=Date.now()+(Number.isFinite(delay)&&delay>0?delay:60)*1000;
        throw new Error(`Wikipedia is rate-limiting requests. Try again in ${Math.ceil((retryAt-Date.now())/60000)} minutes.`);
      }
      if(!response.ok)throw new Error(`Wikipedia request failed (${response.status}).`);
      const raw=await response.text();if(raw.length>250000)throw new Error('Article response exceeded the reading limit.');
      const data=JSON.parse(raw);if(data.error)throw new Error('Wikipedia could not complete this query.');
      const found=(data.query?.pages||[]).filter(p=>p.ns===0&&!p.missing&&p.extract).sort((a,b)=>(a.index||0)-(b.index||0));
      pages=[...pages,...found.filter(p=>!pages.some(q=>q.title===p.title))];
    }
    pages=pages.slice(0,3);
    if(!pages.length)return {text:'No Wikipedia article text found for that query.',sources:[],engine:'wikipedia'};
    const sources=pages.map(p=>({title:p.title,url:'https://en.wikipedia.org/wiki/'+encodeURIComponent(p.title.replaceAll(' ','_')),text:p.extract.slice(0,2500)}));
    return {text:'Wikipedia article excerpts — retrieved online, not generated by the model.\n\n'+sources.map((p,i)=>`[${i+1}] ${p.title}\n${p.text}\nSource: ${p.url}`).join('\n\n')+'\n\nWikipedia contributors · CC BY-SA 4.0. Excerpts may be shortened. Use /web read TITLE to read an article.',sources,engine:'wikipedia'};
  } catch(error) {
    if(error.name==='AbortError')throw new Error('Web lookup stopped or timed out.');
    throw error;
  } finally {clearTimeout(timer);signal?.removeEventListener('abort',abort);}
}
